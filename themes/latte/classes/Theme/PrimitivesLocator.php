<?php

declare(strict_types=1);

namespace WPFasty\Theme;

/**
 * Resolves UI8Kit Latte primitives directory for monorepo + vendored installs.
 */
final class PrimitivesLocator
{
    public static function resolve(?string $themeDir = null): ?string
    {
        $themeDir ??= get_template_directory();

        foreach (self::candidates($themeDir) as $dir) {
            if (is_dir($dir)) {
                return $dir;
            }
        }

        return null;
    }

    /** @return list<string> */
    public static function candidates(string $themeDir): array
    {
        return [
            dirname($themeDir, 2) . '/.workspaces/ui8kit-latte/ui',
            $themeDir . '/lib/ui8kit-latte/ui',
            $themeDir . '/vendor/ui8kit/latte-primitives/ui',
            $themeDir . '/vendor/ui8kit/ui',
        ];
    }

    /**
     * Twig primitives generated by ui8kit/codegen (`generated/ui/<brick>/<Part>.html.twig`).
     * Release builds with the Twig engine (`theme:pack -- latte --engine twig`) bundle them as
     * `lib/ui8kit-twig/{generated/ui,runtime/php}` — the same layout as the codegen package.
     */
    public static function resolveTwig(?string $themeDir = null): ?string
    {
        $themeDir ??= get_template_directory();
        $candidates = [
            $themeDir . '/lib/ui8kit-twig/generated/ui',
            dirname($themeDir, 2) . '/packages/ui8kit-codegen/generated/ui',
        ];
        foreach ($candidates as $dir) {
            if (is_dir($dir)) {
                $twigExtension = dirname($dir, 2) . '/runtime/php/TwigExtension.php';
                if (!class_exists(\UI8Kit\TwigExtension::class) && is_file($twigExtension)) {
                    require_once $twigExtension;
                }
                return $dir;
            }
        }
        return null;
    }
}
