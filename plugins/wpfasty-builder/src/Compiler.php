<?php

declare(strict_types=1);

namespace WPFastyBuilder;

/**
 * Turns a layout entry into a plain page template — Latte (one {=wpfb_block(...)} call per block, props as a Latte
 * array literal) or its Twig twin ({{ wpfb_block(...)|raw }}, props as a Twig hash) from the same entry. Bound
 * paths are not literal: they read wpfb[<block id>][<path>], which the plugin fills from WordPress data through
 * the `wpfasty_context` filter. The Latte page names blocks/<name>.latte, the Twig page blocks/<name>.html.twig:
 * BlockRenderer renders each with its own engine from the source's generated Latte / Twig package (same DOM).
 */
final class Compiler
{
    public const ENGINES = ['latte' => '.latte', 'twig' => '.html.twig'];

    /**
     * First line of a compiled template of $engine (staleness marker).
     *
     * @param array<string, mixed> $entry
     */
    public static function marker(array $entry, string $engine = 'latte'): string
    {
        return $engine === 'twig' ? '{# wpfb:' . self::hash($entry) . ' #}' : '{* wpfb:' . self::hash($entry) . ' *}';
    }

    /** @param array<string, mixed> $entry */
    public static function compile(array $entry, Catalog $catalog, string $engine = 'latte'): string
    {
        $twig = $engine === 'twig';
        [$open, $close] = $twig ? ['{#', '#}'] : ['{*', '*}'];
        $source = (string) ($entry['metadata']['source']['value'] ?? '');
        $lines = [
            self::marker($entry, $engine),
            $open . ($twig ? '' : '*'),
            ' * ' . self::comment((string) ($entry['title'] ?? '')) . ' — generated by WP FastY Builder from layout '
                . self::comment((string) ($entry['id'] ?? '')) . ' v' . (int) ($entry['version'] ?? 1) . '.',
            ' * Do not edit: the builder rewrites this file on save. Context: wpfb (bound data by block id and path).',
            ' ' . $close,
            '<div class="wpfb-page" data-wpfb-layout="' . self::attr((string) ($entry['id'] ?? '')) . '">',
        ];
        foreach (Layout::blocks($entry) as $b) {
            $variant = $catalog->variant((string) $b['block'], (string) $b['variant']);
            $template = (string) ($variant['template'] ?? '');
            // Only templates of the page's own runtime: a catalog of the other runtime is never substituted.
            $own = str_ends_with($template, self::ENGINES[$engine] ?? '-');
            if ($variant === null || preg_match(Catalog::TEMPLATE, $template) !== 1 || !$own) {
                $lines[] = $open . ' skipped: unknown block ' . self::comment($b['block'] . '/' . $b['variant']) . ' '
                    . $close;
                continue;
            }
            $props = self::blockProps($variant, $b);
            $exprs = [];
            foreach (array_keys($b['bindings']) as $path) {
                $exprs[(string) $path] = ($twig ? 'wpfb[' : '$wpfb[') . self::str((string) $b['id']) . ']['
                    . self::str((string) $path) . '] ?? []';
            }
            $lines[] = '<div class="wpfb-block" data-wpfb-block="' . self::attr((string) $b['id']) . '">';
            $call = 'wpfb_block(' . self::str($source) . ', ' . self::str($template) . ', '
                . self::literal($props, [], $exprs, $twig) . ')';
            $lines[] = $twig ? '{{ ' . $call . '|raw }}' : '{=' . $call . '|noescape}';
            $lines[] = '</div>';
        }
        $lines[] = '</div>';
        return implode("\n", $lines) . "\n";
    }

    /**
     * The props a block renders with: the variant sample props, the block's overrides on top, the kind-aware read
     * label; every bound path is null (the page fills it from wpfb[<block id>][<path>], Fragment from the data).
     *
     * @param array<string, mixed> $variant
     * @param array<string, mixed> $b       a block of Layout::blocks()
     * @return array<string, mixed>
     */
    public static function blockProps(array $variant, array $b): array
    {
        $props = self::readLabel(Layout::merge((array) ($variant['props'] ?? []), (array) $b['props']), $b);
        foreach (array_keys((array) $b['bindings']) as $path) {
            Layout::set($props, explode('.', (string) $path), null);
        }
        return $props;
    }

    /**
     * A PHP/Latte array literal (or, with $twig, a Twig hash/list) of a JSON value; the paths in $exprs become
     * those expressions.
     *
     * @param list<string>          $path
     * @param array<string, string> $exprs
     */
    public static function literal(mixed $v, array $path, array $exprs, bool $twig = false): string
    {
        $key = implode('.', $path);
        if ($path !== [] && isset($exprs[$key])) {
            return '(' . $exprs[$key] . ')';
        }
        if (is_array($v)) {
            if ($v === []) {
                return '[]';
            }
            $parts = [];
            $list = array_is_list($v);
            foreach ($v as $k => $x) {
                $val = self::literal($x, [...$path, (string) $k], $exprs, $twig);
                $parts[] = $list ? $val : self::str((string) $k) . ($twig ? ': ' : ' => ') . $val;
            }
            return $list || !$twig ? '[' . implode(', ', $parts) . ']' : '{' . implode(', ', $parts) . '}';
        }
        if (is_string($v)) {
            return self::str($v);
        }
        if (is_bool($v)) {
            return $v ? 'true' : 'false';
        }
        if (is_int($v)) {
            return (string) $v;
        }
        if (is_float($v)) {
            return is_finite($v) ? var_export($v, true) : '0';
        }
        return 'null';
    }

    /**
     * Kind-aware default for the card link label ("Read the post" in the samples): when the block's list is bound
     * to projects, products or pages and the layout did not set labels.read itself, use a label for that kind.
     *
     * @param array<string, mixed> $props
     * @param array<string, mixed> $block
     * @return array<string, mixed>
     */
    public static function readLabel(array $props, array $block): array
    {
        if (!is_array($props['labels'] ?? null) || !isset($props['labels']['read'])) {
            return $props;
        }
        if (isset($block['props']['labels']['read'])) {
            return $props;
        }
        $labels = [
            'projects' => __('View project', 'wpfasty-builder'),
            'products' => __('View product', 'wpfasty-builder'),
            'pages' => __('Read more', 'wpfasty-builder'),
        ];
        foreach ((array) ($block['bindings'] ?? []) as $binding) {
            $source = is_array($binding) ? (string) ($binding['source'] ?? '') : '';
            if (isset($labels[$source])) {
                $props['labels']['read'] = $labels[$source];
                break;
            }
        }
        return $props;
    }

    /** @param array<string, mixed> $entry */
    public static function hash(array $entry): string
    {
        return md5((string) json_encode($entry) . '|' . filemtime(__FILE__));
    }

    public static function str(string $s): string
    {
        return "'" . strtr($s, ['\\' => '\\\\', "'" => "\\'"]) . "'";
    }

    private static function attr(string $s): string
    {
        return htmlspecialchars($s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }

    private static function comment(string $s): string
    {
        return str_replace(['*}', '{*', '#}', '{#', "\n"], ['', '', '', '', ' '], $s);
    }
}
