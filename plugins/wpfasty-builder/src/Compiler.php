<?php

declare(strict_types=1);

namespace WPFastyBuilder;

/**
 * Turns a layout entry into a plain page template — Latte (one {=wpfb_block(...)} call per block, props as a Latte
 * array literal) or its Twig twin ({{ wpfb_block(...)|raw }}, props as a Twig hash) from the same entry. Every prop
 * is a literal: there are no data bindings (ADR-007). The Latte page names blocks/<name>.latte, the Twig page blocks/<name>.html.twig:
 * BlockRenderer renders each with its own engine from the source's generated Latte / Twig package (same DOM).
 *
 * @phpstan-import-type LayoutBlock from Layout
 */
final class Compiler
{
    public const ENGINES = ['latte' => '.latte', 'twig' => '.html.twig'];

    /**
     * First line of a compiled template of $engine (staleness marker).
     *
     * @param array<string, mixed> $entry
     */
    public static function marker(array $entry, string $engine = 'latte'): string
    {
        return 'twig' === $engine ? '{# wpfb:'.self::hash($entry).' #}' : '{* wpfb:'.self::hash($entry).' *}';
    }

    /** @param array<string, mixed> $entry */
    public static function compile(array $entry, Catalog $catalog, string $engine = 'latte'): string
    {
        $twig = 'twig' === $engine;
        [$open, $close] = $twig ? ['{#', '#}'] : ['{*', '*}'];
        $source = Cast::string(Cast::path($entry, 'metadata', 'source', 'value'));
        $lines = [
            self::marker($entry, $engine),
            $open.($twig ? '' : '*'),
            ' * '.self::comment(Cast::string($entry['title'] ?? '')).' — generated by WP FastY Builder from layout '
                .self::comment(Cast::string($entry['id'] ?? '')).' v'.Cast::int($entry['version'] ?? 1).'.',
            ' * Do not edit: the builder rewrites this file on save.',
            ' '.$close,
            '<div class="wpfb-page" data-wpfb-layout="'.self::attr(Cast::string($entry['id'] ?? '')).'">',
        ];
        foreach (Layout::blocks($entry) as $b) {
            $variant = $catalog->variant(Cast::string($b['block']), Cast::string($b['variant']));
            $template = Cast::string($variant['template'] ?? '');
            // Only templates of the page's own runtime: a catalog of the other runtime is never substituted.
            $own = str_ends_with($template, self::ENGINES[$engine] ?? '-');
            if (null === $variant || 1 !== preg_match(Catalog::TEMPLATE, $template) || !$own) {
                $lines[] = $open.' skipped: unknown block '.self::comment($b['block'].'/'.$b['variant']).' '
                    .$close;
                continue;
            }
            $props = self::blockProps($variant, $b);
            $lines[] = '<div class="wpfb-block" data-wpfb-block="'.self::attr(Cast::string($b['id'])).'">';
            $call = 'wpfb_block('.self::str($source).', '.self::str($template).', '
                .self::literal($props, $twig).')';
            $lines[] = $twig ? '{{ '.$call.'|raw }}' : '{='.$call.'|noescape}';
            $lines[] = '</div>';
        }
        $lines[] = '</div>';

        return implode("\n", $lines)."\n";
    }

    /**
     * The props a block renders with: the variant sample props with the block's overrides on top. No trusted markup
     * survives here (Layout::untrust).
     *
     * @param array<string, mixed> $variant
     * @param LayoutBlock          $b       a block of Layout::blocks()
     *
     * @return array<string, mixed>
     */
    public static function blockProps(array $variant, array $b): array
    {
        return Cast::map(Layout::untrust(Layout::merge((array) ($variant['props'] ?? []), $b['props'])));
    }

    /** A PHP/Latte array literal (or, with $twig, a Twig hash/list) of a JSON value. */
    public static function literal(mixed $v, bool $twig = false): string
    {
        if (is_array($v)) {
            if ([] === $v) {
                return '[]';
            }
            $parts = [];
            $list = array_is_list($v);
            foreach ($v as $k => $x) {
                $val = self::literal($x, $twig);
                $parts[] = $list ? $val : self::str((string) $k).($twig ? ': ' : ' => ').$val;
            }

            return $list || !$twig ? '['.implode(', ', $parts).']' : '{'.implode(', ', $parts).'}';
        }
        if (is_string($v)) {
            return self::str($v);
        }
        if (is_bool($v)) {
            return $v ? 'true' : 'false';
        }
        if (is_int($v)) {
            return (string) $v;
        }
        if (is_float($v)) {
            return is_finite($v) ? var_export($v, true) : '0';
        }

        return 'null';
    }

    /** @param array<string, mixed> $entry */
    public static function hash(array $entry): string
    {
        return md5(json_encode($entry).'|'.filemtime(__FILE__));
    }

    /**
     * A single-quoted string literal of both engines: backslash and quote escaped, control characters (which Latte
     * refuses in a template) dropped. Data never leaves the literal: neither engine interpolates single quotes.
     */
    public static function str(string $s): string
    {
        return "'".strtr(Safe::text($s), ['\\' => '\\\\', "'" => "\\'"])."'";
    }

    /**
     * Text inside a template comment ({* … *} / {# … #}): no brace at all, so nothing (`**}}`, `#}`, `*}`) can close
     * the comment and open template code (SSTI: the page title is a layout field), no control character or newline.
     */
    public static function comment(string $s): string
    {
        return trim((string) preg_replace('/[{}\x00-\x1F\x7F]+/', ' ', $s));
    }

    /** an attribute value in the static part of the template: HTML-escaped, and no brace can open a tag of either engine */
    private static function attr(string $s): string
    {
        return strtr(htmlspecialchars(Safe::text($s), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'), [
            '{' => '&#123;',
            '}' => '&#125;',
        ]);
    }
}
