// Builds ../assets/blocks.css: the Tailwind v4 utilities used by the block templates of the bundled source, the
// kit rules of codegen-x (styles/kit.css) and token fallbacks, every selector scoped to .wpfb-page so the sheet
// cannot change the theme outside builder pages. No preflight: the theme owns the base styles.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "sources", "ui8kit");
const themeCss = readFileSync(join(src, "styles", "theme.css"), "utf8");
const kitCss = readFileSync(join(src, "styles", "kit.css"), "utf8");
const inline = themeCss.match(/@theme inline \{[\s\S]*?\n\}/)?.[0];
if (!inline) throw new Error("no @theme inline block in styles/theme.css");
const kit = kitCss.replace(/@layer base \{[\s\S]*?\n\}\n/, "");

// tokens the kit reads that a WP FastY theme may not define: fall back to the shadcn names every theme has
const fallbacks = {
  popover: "var(--card, #fff)", "popover-foreground": "var(--card-foreground, #0a0a0a)",
  "chart-1": "var(--primary)", "chart-2": "var(--accent-foreground, var(--primary))", "chart-3": "var(--muted-foreground)",
  "chart-4": "var(--secondary-foreground)", "chart-5": "var(--ring)",
  sidebar: "var(--card)", "sidebar-foreground": "var(--card-foreground)", "sidebar-primary": "var(--primary)",
  "sidebar-primary-foreground": "var(--primary-foreground)", "sidebar-accent": "var(--accent)",
  "sidebar-accent-foreground": "var(--accent-foreground)", "sidebar-border": "var(--border)", "sidebar-ring": "var(--ring)",
  radius: "0.625rem",
};
const tmp = join(here, ".css-build");
rmSync(tmp, { recursive: true, force: true });
mkdirSync(tmp, { recursive: true });
const input = `@layer theme, base, components, utilities;
@import "tailwindcss/theme.css" layer(theme);
@import "tailwindcss/utilities.css" layer(utilities);
@source "${join(src, "latte")}";
@custom-variant dark (&:is(.dark *, [data-theme="dark"] *));
${inline}
@layer base {
  :where(:root) { ${Object.entries(fallbacks).map(([k, v]) => `--${k}: ${v};`).join(" ")} }
}
${kit}
`;
writeFileSync(join(tmp, "in.css"), input);
execFileSync(join(here, "node_modules", ".bin", "tailwindcss"), ["-i", join(tmp, "in.css"), "-o", join(tmp, "out.css"), "--minify"], { cwd: here, stdio: "inherit" });

const SCOPE = ".wpfb-page";
const keep = (s) => /^(:root|:where\(:root\)|html|body|:host)\b/.test(s);
const scoped = postcss([{
  postcssPlugin: "wpfb-scope",
  Rule(rule) {
    if (rule.parent?.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return;
    if (rule.__scoped) return;
    rule.__scoped = true;
    rule.selectors = rule.selectors.map((s) => (keep(s) ? s : s.startsWith("&") ? s : `${SCOPE} ${s}`));
  },
}]).process(readFileSync(join(tmp, "out.css"), "utf8"), { from: undefined }).css;
const header = "/* WP FastY Builder: block styles (Tailwind v4 utilities + codegen-x kit), scoped to .wpfb-page. Generated by editor/build-css.mjs; do not edit. */\n";
writeFileSync(join(here, "..", "assets", "blocks.css"), header + scoped);
rmSync(tmp, { recursive: true, force: true });
console.log(`assets/blocks.css ${(Buffer.byteLength(scoped) / 1024).toFixed(0)} KB`);
