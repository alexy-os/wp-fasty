// Expected Codex entries of the live /wp/v2 samples (tests/fixtures/codex/wordpress/{media,users}.edit.json, copies of
// ui8kit/contract fixtures/wordpress at the pinned commit) through the contract adapter fromWpMedia / fromWpUser,
// canonical bytes. tests/CodexWpSamplesTest.php maps the same samples with the PHP Mapper and compares.
//   CODEX_CONTRACT=/path/to/built/contract bun tools/codex/wp-samples-expected.ts [--check]
// Locale en-US (settings.language of the samples' site); the owner of media 11 (post 10) is a product.
// Norm (XGenBot): user meta persisted_preferences (editor UI state) never reaches public metadata — the contract
// adapter drops it since a0ae505; no local post-processing.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(dirname(new URL(import.meta.url).pathname), "../..");
const contractDir = resolve(process.env.CODEX_CONTRACT ?? join(root, "node_modules/@ui8kit/contract"));
const C: any = { ...(await import(join(contractDir, "dist/index.js"))), ...(await import(join(contractDir, "dist/adapters/wordpress.js"))) };
const dir = join(root, "tests/fixtures/codex/wordpress");
const read = (f: string) => JSON.parse(readFileSync(join(dir, `${f}.json`), "utf8"));
const OWNER: Record<number, string> = { 10: "product" };
const out = {
  note: "generated by tools/codex/wp-samples-expected.ts (contract adapter fromWpMedia/fromWpUser, canonical bytes)",
  media: read("media.edit").map((m: any) => C.canonicalize(JSON.stringify(C.fromWpMedia(m, { locale: "en-US", resolveKind: (id: number) => OWNER[id] })))),
  users: read("users.edit").map((u: any) => C.canonicalize(JSON.stringify(C.fromWpUser(u, { locale: "en-US" })))),
};
const text = JSON.stringify(out, null, 2) + "\n";
const file = join(dir, "expected.json");
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== text) { console.error(`${file} is stale`); process.exit(1); }
  console.log("✓ expected.json matches the contract adapter");
} else writeFileSync(file, text);
